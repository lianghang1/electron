/** 合法音节集合（从字库派生，单一数据源） */
const SYLLABLES = new Set(Object.keys(PINYIN_CANDIDATES))

export interface SpellSplit {
  /** 已切出的完整音节（从左到右） */
  parts: string[]
  /** 切不出音节的尾串（继续输入或退格） */
  tail: string
}

/**
 * 贪心最长匹配切分拼音串："liming" → ["li","ming"]；"lim" → ["li"] + 尾 "m"。
 * 候选字永远针对 parts[0]（从左往右逐字选定，选定后从串头移除）。
 */
export function splitSpell(spell: string): SpellSplit {
  const parts: string[] = []
  let rest = spell
  while (rest) {
    let hit = ''
    for (let end = Math.min(rest.length, 6); end >= 1; end--) {
      if (SYLLABLES.has(rest.slice(0, end))) {
        hit = rest.slice(0, end)
        break
      }
    }
    if (!hit)
      return { parts, tail: rest }
    parts.push(hit)
    rest = rest.slice(hit.length)
  }
  return { parts, tail: '' }
}
